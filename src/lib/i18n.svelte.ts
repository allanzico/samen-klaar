function initialLocale(): Locale {
  try {
    const saved = typeof localStorage !== 'undefined' ? localStorage.getItem('samenklaar.locale') : null;
    if (saved === 'en' || saved === 'nl') return saved;
  } catch { /* Fall back to the browser language if storage is unavailable. */ }
  return typeof navigator !== 'undefined' && navigator.language.toLowerCase().startsWith('nl') ? 'nl' : 'en';
}

export const localeState = $state({ value: initialLocale() });

export function currentLocale(): Locale { return localeState.value; }

export function setLocale(value: Locale) {
  localeState.value = value;
  try { if (typeof localStorage !== 'undefined') localStorage.setItem('samenklaar.locale', value); } catch { /* The selection still applies for this page. */ }
  if (typeof document !== 'undefined') document.documentElement.lang = localeState.value;
}

export function t(source: string, values: Record<string, string | number> = {}): string {
  let result = translations[localeState.value][source] ?? source;
  for (const [key, value] of Object.entries(values)) result = result.split(`{${key}}`).join(String(value));
  return result;
}
